#!/usr/bin/env python3
"""Write a state's one-page report (<out>/<st>/report.md) from the history database.

The report flags events with simple fixed rules so a person can review them. These rules are
for reading the history, not the auditor's checks: those are built per state from the
profiles after review (plan, sections 2 Q15-Q16 and 6).

usage: python3 report.py [--db history.sqlite] [--out <folder>] wy ky ar
"""
from __future__ import annotations

import argparse
import json
import re
import sqlite3
import sys
from collections import defaultdict
from pathlib import Path

DEFAULT_OUT = Path("/Volumes/govbot-data/scratch/history-analysis")
BARS = " ▁▂▃▄▅▆▇█"


def bar(n: float, top: float, width: int = 20) -> str:
    return "█" * round(width * n / top) if top else ""


def runs(rows, pred):
    """Consecutive runs of rows where pred(row) holds: [(first, last, count)]."""
    out, start, prev, n = [], None, None, 0
    for r in rows:
        if pred(r):
            if start is None:
                start, n = r, 0
            prev, n = r, n + 1
        elif start is not None:
            out.append((start, prev, n))
            start = None
    if start is not None:
        out.append((start, prev, n))
    return out


def ex(js: str, key: str) -> str:
    vals = json.loads(js or "{}").get(key) or []
    return ", ".join(str(v) for v in vals)


ID_NUM = re.compile(r"^([A-Za-z]+)\s*0*(\d+)$")


def numbering_gaps(idents: list[str], limit: int = 15) -> list[str]:
    """Per letter prefix (HB, SF...), the numbers missing up to the highest seen."""
    by_prefix: dict[str, dict[int, str]] = defaultdict(dict)
    for i in idents:
        m = ID_NUM.match(i.strip())
        if m:
            by_prefix[m.group(1).upper()][int(m.group(2))] = i
    out = []
    for prefix, nums in sorted(by_prefix.items()):
        top = max(nums)
        if len(nums) < 5:
            continue
        # From 1, unless numbering plainly starts higher (AR's House bills start at 1001).
        low = 1 if min(nums) <= 10 else min(nums)
        missing = [n for n in range(low, top + 1) if n not in nums]
        if missing:
            width = max(len(re.sub(r"^[A-Za-z]+\s*", "", v)) for v in nums.values())
            shown = ", ".join(f"{prefix}{str(n).zfill(width)}" for n in missing[:limit])
            more = f" … +{len(missing) - limit} more" if len(missing) > limit else ""
            out.append(f"{prefix}: {len(missing)} of {low}–{top} missing ({shown}{more})")
    return out


def write_report(con: sqlite3.Connection, state: str, path: Path) -> None:
    con.row_factory = sqlite3.Row
    q = lambda sql, *a: con.execute(sql, (state, *a)).fetchall()
    run = q("SELECT * FROM runs WHERE state = ?")
    scr = q("SELECT * FROM scrapes WHERE state = ? ORDER BY idx")
    L: list[str] = []
    w = L.append
    w(f"# {state.upper()}: raw scrape history\n")
    if not scr:
        w("No scrapes.\n")
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text("\n".join(L))
        return
    r0 = run[0] if run else None
    w(f"{len(scr)} scrapes, {scr[0]['committed_at'][:10]} to {scr[-1]['committed_at'][:10]}. "
      f"Generated by `actions/openstates-scrape-audits/history/scan.py`"
      + (f" at {r0['scanner_commit'][:9]}{' (uncommitted changes)' if r0['scanner_dirty'] else ''},"
         f" raw HEAD {r0['raw_head'][:9]}, {r0['seconds']} s." if r0 and r0['scanner_commit'] else ".") + "\n")
    w("Rules here only flag things for a person to review; they are not the auditor's checks.\n")
    import known_events  # same folder
    if known_events.CAVEATS.get(state):
        w("**Read this state's numbers with care. Its raw history misleads in known ways** "
          "(`known_events.CAVEATS`; the state file has the evidence):\n")
        for c in known_events.CAVEATS[state]:
            w(f"- {c}")
        w("")

    # --- Monthly chart
    w("## Month by month\n")
    months = defaultdict(list)
    for r in scr:
        months[r["committed_at"][:7]].append(r)
    top = max(r["bills"] for r in scr) or 1
    w("| Month | Scrapes | Most bills | Empty scrapes | Unchanged scrapes | New actions | New votes | |")
    w("|---|---|---|---|---|---|---|---|")
    for m, rs in sorted(months.items()):
        mx = max(r["bills"] for r in rs)
        w(f"| {m} | {len(rs)} | {mx:,} | {sum(r['bills'] == 0 for r in rs)} | "
          f"{sum(r['identical_content'] for r in rs)} | {sum(r['actions_new'] for r in rs):,} | "
          f"{sum(r['votes_new'] for r in rs):,} | `{bar(mx, top)}` |")
    w("")

    # --- Outages
    w("## Outages: scrapes with no bills, or nothing changed\n")
    empty = runs(scr, lambda r: r["bills"] == 0)
    w(f"**Scrapes with 0 readable bills: {sum(n for *_, n in empty)}** "
      f"({sum(r['bill_files'] == 0 for r in scr)} with 0 bill files). Each run below is one outage: the "
      f"`scrapes` table counts its bills as gone at its first scrape and returned after it, and they are not "
      f"listed again under \"Bills that dropped out\".\n")
    for a, b, n in empty:
        w(f"- {a['committed_at'][:10]} to {b['committed_at'][:10]}: {n} scrapes "
          f"(bill files: {a['bill_files']}; other files: {a['other_files']}; commits {a['sha'][:9]} … {b['sha'][:9]})")
    gaps = [r for r in scr if (r["gap_hours"] or 0) >= 72]
    w(f"\n**Gaps of 3+ days with no scrape committed: {len(gaps)}**\n")
    for r in gaps:
        w(f"- {r['gap_hours'] / 24:.1f} days before {r['committed_at'][:10]}")
    frozen = [x for x in runs(scr, lambda r: r["identical_content"] and r["bills"] > 0) if x[2] >= 3]
    w(f"\n**Runs of 3+ scrapes identical to the one before (bills and votes, minus scraped_at/_id): {len(frozen)}**\n")
    for a, b, n in frozen:
        w(f"- {a['committed_at'][:10]} to {b['committed_at'][:10]}: {n} scrapes, {a['bills']:,} bills")
    quiet = [x for x in runs(scr, lambda r: r["bills"] > 0 and r["actions_new"] == 0 and r["votes_new"] == 0
                                            and r["bills_new"] == 0) if x[2] >= 14]
    w(f"\n**Runs of 14+ scrapes with no new bill, action or vote: {len(quiet)}** (normal out of session)\n")
    for a, b, n in quiet:
        w(f"- {a['committed_at'][:10]} to {b['committed_at'][:10]}: {n} scrapes")
    w("")

    # --- Bills dropped
    w("## Bills that dropped out\n")
    w("Scrapes (with bills) where at least 5 bills and 2% of the previous scrape's bills went missing.\n")
    prev = None
    rows = []
    for r in scr:
        if prev is not None and r["bills"] > 0 and r["bills_gone"] >= max(5, 0.02 * (prev["bills"] or 0)):
            rows.append((r, prev))
        prev = r
    if rows:
        w("| Scrape | Bills before → now | Gone | Came back later | Sessions that left the scrape | Examples |")
        w("|---|---|---|---|---|---|")
        for r, p in rows:
            before, after = json.loads(p["bills_by_session"]), json.loads(r["bills_by_session"])
            left = ", ".join(f"`{s}` ({n:,})" for s, n in before.items() if s not in after)
            w(f"| {r['committed_at'][:10]} `{r['sha'][:9]}` | {p['bills']:,} → {r['bills']:,} | {r['bills_gone']:,} | "
              f"{r['bills_gone_back']:,} | {left} | {ex(r['examples'], 'bills_gone')} |")
    else:
        w("None.")
    gfg = q("SELECT session, identifier, last_at FROM bills WHERE state = ? AND gone_for_good AND session_continued "
            "ORDER BY last_at")
    w(f"\n**Bills gone for good while their session went on: {len(gfg)}**\n")
    by_last = defaultdict(list)
    for b in gfg:
        by_last[b["last_at"][:10]].append(f"{b['session']} {b['identifier']}")
    for d, bs in sorted(by_last.items(), key=lambda x: -len(x[1]))[:10]:
        w(f"- last seen {d}: {len(bs)} ({', '.join(bs[:3])})")
    w("")

    # --- Field losses
    w("## Fields that went empty\n")
    w("Scrape/field rows where at least 5 bills, and 20% of the bills that had the field, lost it.\n")
    fl = q("SELECT * FROM scrape_fields WHERE state = ? AND lost >= 5 AND lost >= 0.2 * had ORDER BY idx, field")
    if fl:
        w("| Scrape | Field | Lost / had | Came back later | Examples |")
        w("|---|---|---|---|---|")
        for r in fl[:60]:
            w(f"| {r['committed_at'][:10]} | `{r['field']}` | {r['lost']:,} / {r['had']:,} "
              f"({100 * r['lost'] / r['had']:.0f}%) | {r['lost_back']:,} | {ex(r['examples'], 'lost')} |")
        if len(fl) > 60:
            w(f"\n… {len(fl) - 60} more rows in `scrape_fields`.")
    else:
        w("None.")
    w("")

    # --- Shape changes
    w("## Reshaped data\n")
    rew = [r for r in scr if r["actions_reworded"] >= 20 or r["actions_ws_only"] >= 20 or r["sponsors_renamed"] >= 10
           or r["actions_chamber_swapped"] >= 20]
    w(f"Reworded actions in all: {sum(r['actions_reworded'] for r in scr):,}; whitespace-only action changes: "
      f"{sum(r['actions_ws_only'] for r in scr):,}; actions back under another chamber: "
      f"{sum(r['actions_chamber_swapped'] for r in scr):,}; bills with a renamed sponsor: "
      f"{sum(r['sponsors_renamed'] for r in scr):,}.\n")
    for r in rew[:30]:
        parts = []
        if r["actions_reworded"]:
            parts.append(f"{r['actions_reworded']:,} reworded ({ex(r['examples'], 'reworded_top')})")
        if r["actions_ws_only"]:
            parts.append(f"{r['actions_ws_only']:,} whitespace-only")
        if r["actions_chamber_swapped"]:
            parts.append(f"{r['actions_chamber_swapped']:,} under another chamber ({ex(r['examples'], 'chamber_swap_top')})")
        if r["sponsors_renamed"]:
            parts.append(f"{r['sponsors_renamed']:,} sponsors renamed ({ex(r['examples'], 'sponsor_rename_top')})")
        w(f"- {r['committed_at'][:10]}: " + "; ".join(parts))
    ws = q("SELECT committed_at, field, ws_only, changed FROM scrape_fields WHERE state = ? AND ws_only >= 20 ORDER BY idx")
    for r in ws[:20]:
        w(f"- {r['committed_at'][:10]}: `{r['field']}` changed only in whitespace on {r['ws_only']:,} bills")
    w("")

    # --- Actions and votes lost
    w("## Actions and votes that disappeared\n")
    ag = [r for r in scr if r["actions_gone"] >= 20]
    w(f"Actions gone from a bill still present, in all: {sum(r['actions_gone'] for r in scr):,}. "
      f"Votes gone while their bill was present: {sum(r['votes_gone'] - r['votes_rekeyed'] for r in scr):,}.\n")
    for r in ag[:20]:
        w(f"- {r['committed_at'][:10]}: {r['actions_gone']:,} actions gone ({ex(r['examples'], 'actions_gone')})")
    vg = [r for r in scr if r["votes_gone"] - r["votes_rekeyed"] >= 20]
    for r in vg[:20]:
        w(f"- {r['committed_at'][:10]}: {r['votes_gone'] - r['votes_rekeyed']:,} votes gone ({ex(r['examples'], 'votes_gone')})")
    rk = [r for r in scr if r["votes_rekeyed"] >= 20]
    w(f"\nVotes back under another key (same bill, same day and voters or motion), in all: "
      f"{sum(r['votes_rekeyed'] for r in scr):,}; they're not counted as gone below.\n")
    for r in rk[:20]:
        w(f"- {r['committed_at'][:10]}: {r['votes_rekeyed']:,} re-keyed ({ex(r['examples'], 'rekeyed_fields')})")
    tot = con.execute("SELECT SUM(actions_gone_for_good), SUM(votes_gone_for_good), SUM(votes_ever) FROM bills "
                      "WHERE state = ?", (state,)).fetchone()
    w(f"\nNever came back: {tot[0] or 0:,} actions, {tot[1] or 0:,} of {tot[2] or 0:,} votes (compared with each "
      f"bill's last scrape).\n")

    # --- Roll calls
    w("## Roll calls\n")
    kinds = [("votes_empty", "no voters"), ("votes_emptied", "emptied (had voters before)"),
             ("votes_error_voters", "error text as a voter"), ("votes_page_text", "page text as a voter"),
             ("votes_count_mismatch", "counts don't match the voter list"), ("votes_orphan", "bill not in the scrape")]
    w("| Problem | Scrapes with any | Most in one scrape | Worst scrape | Examples |")
    w("|---|---|---|---|---|")
    for col, label in kinds:
        hit = [r for r in scr if r[col]]
        if not hit:
            w(f"| {label} | 0 | | | |")
            continue
        worst = max(hit, key=lambda r: r[col])
        w(f"| {label} | {len(hit)} | {worst[col]:,} | {worst['committed_at'][:10]} | {ex(worst['examples'], col)} |")
    w("")

    # --- Damaged files and duplicates
    w("## Damaged files and duplicates\n")
    bad = [r for r in scr if r["bad_conflict"] or r["bad_invalid"] or r["bad_empty"]]
    if bad:
        for r in bad[:30]:
            w(f"- {r['committed_at'][:10]} `{r['sha'][:9]}`: {r['bad_conflict']} with conflict markers, "
              f"{r['bad_invalid']} invalid JSON, {r['bad_empty']} empty; {r['bad_bills']} bills only in them")
    else:
        w("No unreadable files.")
    with_bills = [r for r in scr if r["bills"]]
    if with_bills:
        worst = max(with_bills, key=lambda r: r["dup_ratio"])
        ratios = sorted(r["dup_ratio"] for r in with_bills)
        w(f"\nBill files per bill: median {ratios[len(ratios) // 2]}, worst {worst['dup_ratio']} on "
          f"{worst['committed_at'][:10]} ({worst['bill_files']:,} files for {worst['bills']:,} bills). "
          f"Scrapes with any duplicate: {sum(r['dup_ratio'] > 1 for r in with_bills)}.")
    w("")

    # --- Sessions
    w("## Sessions: raw history vs the data repo and govbot-archive\n")
    w("`—` = repo not found (or still cloning). A session with bills in the raw history and 0 everywhere else is "
      "really missing.\n")
    w("| Session | Raw first → last | Raw bills (in last scrape) | Data repo | Archive (July) | Archive pre-rebuild | |")
    w("|---|---|---|---|---|---|---|")
    fmt = lambda v: "—" if v is None else f"{v:,}"
    for s in q("SELECT * FROM sessions WHERE state = ? ORDER BY COALESCE(raw_first_at, ''), session"):
        flag = ""
        if s["raw_bills"] and not any((s["data_repo_bills"], s["archive_bills"], s["archive_pre_rebuild_bills"])):
            flag = "**missing everywhere**" if None not in (s["archive_bills"], s["archive_pre_rebuild_bills"]) \
                else "not in data repo; archive unread"
        elif s["raw_bills"] and not s["data_repo_bills"]:
            flag = "not in data repo (in archive)"
        w(f"| `{s['session']}` | {(s['raw_first_at'] or '')[:10]} → {(s['raw_last_at'] or '')[:10]} | "
          f"{s['raw_bills']:,} ({s['raw_bills_last']:,}) | {fmt(s['data_repo_bills'])} | {fmt(s['archive_bills'])} | "
          f"{fmt(s['archive_pre_rebuild_bills'])} | {flag} |")
    w("")
    w("**Numbering gaps** (bill numbers never seen in the raw history, up to the highest; from 1 unless a "
      "prefix's numbers start above 10. Many are normal, e.g. numbers a chamber skips):\n")
    for s in q("SELECT DISTINCT session FROM bills WHERE state = ? ORDER BY session"):
        ids = [r[0] for r in con.execute("SELECT identifier FROM bills WHERE state = ? AND session = ?",
                                         (state, s["session"]))]
        gaps = numbering_gaps(ids)
        w(f"- `{s['session']}`: " + ("; ".join(gaps) if gaps else "none"))
    w("")

    # --- Field inventory
    w("## Field inventory\n")
    w("Share of bills with the field filled, in the latest scrape with bills and at its best. Nested fields, "
      "extras and link media types are in the `fields` table.\n")
    w("| Field | Latest | Best (first reached) | Seen |")
    w("|---|---|---|---|")
    for f in q("SELECT * FROM fields WHERE state = ? AND kind IN ('top', 'media') ORDER BY kind DESC, field"):
        w(f"| `{f['field']}`{' (unusual)' if f['unusual'] else ''} | {100 * (f['share_latest'] or 0):.0f}% | "
          f"{100 * f['best_share']:.0f}% ({(f['best_at'] or '')[:10]}) | {f['first_at'][:10]} → {(f['last_at'] or '')[:10]} |")
    extras = q("SELECT * FROM fields WHERE state = ? AND kind = 'extras' ORDER BY best_share DESC")
    if extras:
        w("\n**`extras` keys** (state-specific information): " + "; ".join(
            f"`{f['field'][7:]}` {100 * f['best_share']:.0f}% (e.g. {f['example']})" for f in extras[:20]))
    w("")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(L) + "\n")


def main(argv=None) -> int:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("states", nargs="+")
    p.add_argument("--out", type=Path, default=DEFAULT_OUT)
    p.add_argument("--db", type=Path)
    a = p.parse_args(argv)
    con = sqlite3.connect(str(a.db or a.out / "history.sqlite"))
    for s in a.states:
        write_report(con, s.lower(), a.out / s.lower() / "report.md")
        print(a.out / s.lower() / "report.md")
    return 0


if __name__ == "__main__":
    sys.exit(main())
